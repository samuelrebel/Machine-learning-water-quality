def atomic_to_csv(df: pd.DataFrame, path: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(prefix="tmp_", suffix=".csv", dir=os.path.dirname(path))
    os.close(fd)
    try:
        df.to_csv(tmp_path, index=False)
        os.replace(tmp_path, path)
    finally:
        try:
            if os.path.exists(tmp_path):
                os.remove(tmp_path)
        except Exception:
            pass


def append_to_csv(df: pd.DataFrame, path: str):
    """
    Incrementeel appenden (checkpoint-friendly).
    """
    if df is None or df.empty:
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path):
        df.to_csv(path, mode="a", header=False, index=False)
    else:
        df.to_csv(path, index=False)


def _normalize_basin_key_series(s: pd.Series) -> pd.Series:
    return s.astype("string").str.replace(r"\.0$", "", regex=True).str.strip()


def prediction_month_columns(df: pd.DataFrame) -> list[str]:
    if df is None or df.empty:
        return []
    return [c for c in df.columns if re.search(r"_(0[1-9]|1[0-2])$", str(c))]


def wide_candidate_paths(wide_path: str) -> list[str]:
    """Return possible current and legacy locations for a scenario wide CSV."""
    scenario_dir = os.path.dirname(wide_path)
    predictions_root = os.path.dirname(scenario_dir)
    output_root = os.path.dirname(predictions_root)
    file_name = os.path.basename(wide_path)
    return list(dict.fromkeys([
        wide_path,
        os.path.join(predictions_root, file_name),
        os.path.join(output_root, file_name),
    ]))


def read_wide_candidate(path: str) -> pd.DataFrame | None:
    if not os.path.exists(path):
        return None
    try:
        df = pd.read_csv(path)
    except Exception as e:
        print(f"⚠️ Kon wide kandidaat niet lezen ({path}): {e}")
        return None
    if "hydrobasin_level12" not in df.columns:
        print(f"⚠️ Wide kandidaat mist hydrobasin_level12 en wordt genegeerd: {path}")
        return None
    df = df.loc[:, ~df.columns.duplicated()].copy()
    df["hydrobasin_level12"] = _normalize_basin_key_series(df["hydrobasin_level12"])
    df = df.drop_duplicates(subset=["hydrobasin_level12"], keep="first")
    return df


def load_or_initialize_wide_predictions(wide_path: str,
                                        pred_feat_use: pd.DataFrame,
                                        meta_cols: list[str]) -> pd.DataFrame:
    """Load bestaande wide predictions en behoud alle bestaande constituent-kolommen.

    Zoekt ook legacy-locaties, bijvoorbeeld direct onder T3/output. De kandidaat
    met de meeste prediction-maandkolommen wint. Daarna wordt het resultaat
    naar de huidige scenario-map teruggeschreven bij de eerstvolgende checkpoint.
    """
    base_meta = pred_feat_use[meta_cols].drop_duplicates(subset=["hydrobasin_level12"]).copy()
    base_meta["hydrobasin_level12"] = _normalize_basin_key_series(base_meta["hydrobasin_level12"])

    candidates = []
    for path in wide_candidate_paths(wide_path):
        df = read_wide_candidate(path)
        if df is None:
            continue
        n_pred = len(prediction_month_columns(df))
        candidates.append((n_pred, path, df))
        print(f"Wide kandidaat gevonden: {path} | prediction month columns={n_pred} | shape={df.shape}")

    if not candidates:
        print(f"Geen bestaande wide CSV gevonden; start nieuw: {wide_path}")
        return base_meta

    candidates.sort(key=lambda x: x[0], reverse=True)
    best_n_pred, best_path, old = candidates[0]
    if best_n_pred == 0:
        print("⚠️ Alleen wide kandidaten zonder prediction-kolommen gevonden; start met actuele meta en voorspel opnieuw.")
        return base_meta

    old_payload = old.drop(columns=[c for c in meta_cols if c != "hydrobasin_level12"], errors="ignore")
    wide = base_meta.merge(old_payload, on="hydrobasin_level12", how="left", validate="1:1")

    pred_cols = prediction_month_columns(wide)
    print(f"Beste bestaande wide CSV geladen: {best_path}")
    print(f"Prediction month columns behouden/gemigreerd: {len(pred_cols)}")
    if best_path != wide_path:
        print(f"Deze wide wordt voortaan weggeschreven naar huidige scenario-locatie: {wide_path}")
    return wide


