def load_obs_files(obs_folder: str) -> dict:
    files = [f for f in os.listdir(obs_folder) if f.endswith('.csv')]
    data = {}
    for f in files:
        df = pd.read_csv(os.path.join(obs_folder, f))
        data[f] = df
    return data

def left_join_site_info(d: dict, site_info_path: str) -> dict:
    site_info_df = pd.read_csv(site_info_path)
    out = {}
    for name, df in d.items():
        out[name] = df.merge(site_info_df, on='wqms_id', how='left')
