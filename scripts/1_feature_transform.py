def _safe_key(s: pd.Series) -> pd.Series:
    s = s.astype("string").str.strip()
    s = s.str.replace(r"\.0$", "", regex=True)
    return s


def ensure_primary_key(df: pd.DataFrame,
                       primary_key: str = PRIMARY_KEY,
                       secondary_key: str = SECONDARY_KEY) -> pd.DataFrame:
    out = df.copy()
    if primary_key not in out.columns:
        if secondary_key in out.columns:
            out[primary_key] = out[secondary_key]
        else:
            out[primary_key] = pd.NA
    out[primary_key] = _safe_key(out[primary_key])

    if secondary_key in out.columns:
        out[secondary_key] = _safe_key(out[secondary_key])
    return out


def sanitize_columns(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()
    out.columns = (
        out.columns
        .str.strip()
        .str.replace(r"[^\w]+", "_", regex=True)
        .str.replace(r"_+", "_", regex=True)
        .str.strip("_")
    )
    out = out.loc[:, ~out.columns.duplicated()]
    return out


def haversine_km(lat1, lon1, lat2, lon2):
    r = 6371.0088
    lat1 = np.deg2rad(lat1)
    lon1 = np.deg2rad(lon1)
    lat2 = np.deg2rad(lat2)
    lon2 = np.deg2rad(lon2)
    dlat = lat2 - lat1
    dlon = lon2 - lon1
    a = np.sin(dlat / 2.0) ** 2 + np.cos(lat1) * np.cos(lat2) * np.sin(dlon / 2.0) ** 2
    return 2.0 * r * np.arcsin(np.sqrt(a))


def normalize_lon_to_grid(lons: np.ndarray, grid_lons: np.ndarray) -> np.ndarray:
    """Align point longitudes to netCDF longitude convention (-180..180 or 0..360)."""
    lons = np.asarray(lons, dtype=float).copy()
    gmin = float(np.nanmin(grid_lons))
    gmax = float(np.nanmax(grid_lons))

    if gmin >= 0 and gmax > 180:
        lons = np.mod(lons, 360.0)
    elif gmin < 0 and gmax <= 180:
        lons = ((lons + 180.0) % 360.0) - 180.0
    return lons


def nearest_index(sorted_vals: np.ndarray, targets: np.ndarray) -> np.ndarray:
    idx = np.searchsorted(sorted_vals, targets, side="left")
    idx = np.clip(idx, 1, len(sorted_vals) - 1)
    left = sorted_vals[idx - 1]
    right = sorted_vals[idx]
    idx -= (np.abs(targets - left) < np.abs(targets - right))
    return idx


def select_linestring(geom):
    if geom is None or geom.is_empty:
        return None
    if isinstance(geom, LineString):
        return geom
    if isinstance(geom, MultiLineString):
        parts = [g for g in geom.geoms if isinstance(g, LineString) and not g.is_empty]
        if not parts:
            return None
        return max(parts, key=lambda g: g.length)
    return None


def read_obs_station_context(obs_folder: str) -> pd.DataFrame:
    if not os.path.isdir(obs_folder):
        return pd.DataFrame(columns=["wqms_id", PRIMARY_KEY, "country_name"])

    files = [os.path.join(obs_folder, f) for f in os.listdir(obs_folder) if f.endswith(".csv")]
    if not files:
        return pd.DataFrame(columns=["wqms_id", PRIMARY_KEY, "country_name"])

    rows = []
    for f in files:
        try:
            tmp = pd.read_csv(f, usecols=lambda c: c in {"wqms_id", PRIMARY_KEY, "country_name"})
            rows.append(tmp)
        except Exception:
            continue

    if not rows:
        return pd.DataFrame(columns=["wqms_id", PRIMARY_KEY, "country_name"])

    obs_ctx = pd.concat(rows, ignore_index=True)
    obs_ctx = ensure_primary_key(obs_ctx)

    # Most frequent basin/country per station for robust reference mapping
    def mode_or_nan(s):
        s = s.dropna()
        if s.empty:
            return pd.NA
        return s.mode().iloc[0]

    return (
        obs_ctx.groupby("wqms_id", as_index=False)
        .agg({PRIMARY_KEY: mode_or_nan, "country_name": mode_or_nan})
        .rename(columns={PRIMARY_KEY: f"{PRIMARY_KEY}_obs", "country_name": "country_name_obs"})
    )


