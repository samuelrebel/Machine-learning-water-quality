def _require_paths_exist(paths: list[str], label: str):
    missing = [p for p in paths if not os.path.exists(p)]
    if missing:
        raise FileNotFoundError(f"[{label}] Ontbrekende paden: {missing}")


def _read_header_cols(csv_path: str) -> list[str]:
    return pd.read_csv(csv_path, nrows=0).columns.tolist()


def run_preflight_checks(
    pollutant_dir: str,
    features_path_europe: str,
    features_path_world: str,
    shared_features_europe: str,
    shared_features_world: str,
    output_base_eu_nl: str,
    output_base_world: str,
    output_files: str,
):
    print("\n=== PREFLIGHT CHECKS ===")

    # 1) Bestanden/mappen bestaan
    _require_paths_exist(
        [pollutant_dir, features_path_europe, features_path_world, shared_features_europe, shared_features_world],
        label="exists"
    )

    # 2) Pollutant files aanwezig
    pollutant_files = list_pollutant_files(pollutant_dir)
    if not pollutant_files:
        raise ValueError(f"Geen pollutant CSV's gevonden in: {pollutant_dir}")
    print(f"✅ Pollutant files gevonden: {len(pollutant_files)}")

    # 3) Vereiste feature-kolommen aanwezig
    req_feature_cols = {"hydrobasin_level12"}
    feat_eu_cols = set(_read_header_cols(features_path_europe))
    feat_w_cols = set(_read_header_cols(features_path_world))

    if not req_feature_cols.issubset(feat_eu_cols):
        raise ValueError(f"Europe features missen verplichte kolommen: {req_feature_cols - feat_eu_cols}")
    if not req_feature_cols.issubset(feat_w_cols):
        raise ValueError(f"World features missen verplichte kolommen: {req_feature_cols - feat_w_cols}")
    print("✅ Feature headers bevatten verplichte basin-key kolommen")

    # 4) Shared feature lists valide
    shared_eu = read_shared_feature_list(shared_features_europe)
    shared_w = read_shared_feature_list(shared_features_world)
    if not shared_eu or not shared_w:
        raise ValueError("Shared feature list is leeg of ongeldig (EU/WORLD).")

    miss_eu = [c for c in shared_eu if c not in feat_eu_cols]
    miss_w = [c for c in shared_w if c not in feat_w_cols]
    if miss_eu:
        raise ValueError(f"Europe features missen shared kolommen (eerste 10): {miss_eu[:10]}")
    if miss_w:
        raise ValueError(f"World features missen shared kolommen (eerste 10): {miss_w[:10]}")
    print(f"✅ Shared features valide (EU={len(shared_eu)}, WORLD={len(shared_w)})")

    # 5) Observatiekolommen in sample controleren (header-only)
    req_obs_cols = {"wqms_id", "obs", "month", "hydrobasin_level12"}
    sample_files = pollutant_files[: min(20, len(pollutant_files))]
    obs_bad = []
    for p in sample_files:
        cols = set(_read_header_cols(p))
        miss = req_obs_cols - cols
        if miss:
            obs_bad.append((os.path.basename(p), sorted(list(miss))))
    if obs_bad:
        raise ValueError(f"Observatiekolommen missen in sample files: {obs_bad[:5]}")
    print(f"✅ Observatieheaders ok in sample van {len(sample_files)} files")

    # 6) Outputmappen schrijfbaar
    for d in [output_base_eu_nl, output_base_world, output_files]:
        os.makedirs(d, exist_ok=True)
    print("✅ Output directories writeable")

    print("=== PREFLIGHT OK ===\n")


