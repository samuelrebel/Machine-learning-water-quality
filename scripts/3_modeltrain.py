def safe_div(numer: float, denom: float, eps: float = 1e-12) -> float:
    if denom is None or np.isnan(denom) or abs(denom) < eps:
        return np.nan
    return float(numer) / float(denom)


def compute_rmse_and_nrmse(y_true: np.ndarray, y_pred: np.ndarray):
    rmse = float(np.sqrt(mean_squared_error(y_true, y_pred)))
    y_mean = float(np.mean(y_true)) if len(y_true) else np.nan
    y_std = float(np.std(y_true, ddof=0)) if len(y_true) else np.nan
    y_range = float(np.max(y_true) - np.min(y_true)) if len(y_true) else np.nan

    return (
        rmse,
        safe_div(rmse, y_mean),
        safe_div(rmse, y_range),
        safe_div(rmse, y_std),
    )


