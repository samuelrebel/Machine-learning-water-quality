def assign_stations_to_basins(stations_gdf: gpd.GeoDataFrame,
                              hydrobasins_gdf: gpd.GeoDataFrame,
                              obs_ctx: pd.DataFrame) -> pd.DataFrame:
    st_join = gpd.sjoin(
        stations_gdf,
        hydrobasins_gdf[[PRIMARY_KEY, SECONDARY_KEY, "continent_tile", "geometry"]],
        how="left",
        predicate="within",
        lsuffix="st",
        rsuffix="hb",
    ).drop(columns=["index_right"], errors="ignore")

    def _pick_col(cols: list[str], base: str, prefer_right: bool = True) -> str | None:
        ordered = [
            f"{base}_hb",
            f"{base}_right",
            base,
            f"{base}_st",
            f"{base}_left",
        ] if prefer_right else [
            base,
            f"{base}_st",
            f"{base}_left",
            f"{base}_hb",
            f"{base}_right",
        ]
        for c in ordered:
            if c in cols:
                return c
        return None

    key_src = _pick_col(list(st_join.columns), PRIMARY_KEY, prefer_right=True)
    hyb_src = _pick_col(list(st_join.columns), SECONDARY_KEY, prefer_right=True)

    st_join[f"{PRIMARY_KEY}_spatial"] = st_join[key_src] if key_src is not None else pd.NA
    st_join[f"{SECONDARY_KEY}_spatial"] = st_join[hyb_src] if hyb_src is not None else pd.NA
    st_join[f"{PRIMARY_KEY}_spatial"] = _safe_key(st_join[f"{PRIMARY_KEY}_spatial"])
    st_join[f"{SECONDARY_KEY}_spatial"] = _safe_key(st_join[f"{SECONDARY_KEY}_spatial"])

    st_df = pd.DataFrame(st_join.drop(columns="geometry", errors="ignore"))
    st_df = st_df.merge(obs_ctx, on="wqms_id", how="left")

    # Canonical primary key decision: prefer obs key when available, else spatial key
    st_df[PRIMARY_KEY] = st_df[f"{PRIMARY_KEY}_obs"].where(st_df[f"{PRIMARY_KEY}_obs"].notna(), st_df[f"{PRIMARY_KEY}_spatial"])
    st_df[PRIMARY_KEY] = _safe_key(st_df[PRIMARY_KEY])

    # Keep HYBAS_ID as mapping/QC field (from spatial basin assignment)
    st_df[SECONDARY_KEY] = _safe_key(st_df.get(f"{SECONDARY_KEY}_spatial", pd.Series(index=st_df.index, dtype="string")))

    # Country fallback
    if "country_name" not in st_df.columns:
        st_df["country_name"] = pd.NA
    st_df["country_name"] = st_df["country_name"].where(st_df["country_name"].notna(), st_df.get("country_name_obs", pd.Series(index=st_df.index, dtype="string")))

    # QC flags
    st_df["qc_has_obs_key"] = st_df[f"{PRIMARY_KEY}_obs"].notna()
    st_df["qc_has_spatial_key"] = st_df[f"{PRIMARY_KEY}_spatial"].notna()
    st_df["qc_obs_vs_spatial_key_mismatch"] = (
        st_df[f"{PRIMARY_KEY}_obs"].notna()
        & st_df[f"{PRIMARY_KEY}_spatial"].notna()
        & (st_df[f"{PRIMARY_KEY}_obs"] != st_df[f"{PRIMARY_KEY}_spatial"])
    )
    st_df["qc_primary_vs_hybasid_mismatch"] = (
        st_df[PRIMARY_KEY].notna()
        & st_df[SECONDARY_KEY].notna()
        & (st_df[PRIMARY_KEY] != st_df[SECONDARY_KEY])
    )

    return st_df


