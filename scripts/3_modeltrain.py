def load_features(features_path: str, shared_features_path: str | None = None):
    if not os.path.exists(features_path):
        raise FileNotFoundError(f"Features-file niet gevonden: {features_path}")

    df = pd.read_csv(features_path)
    df.columns = df.columns.str.strip()
    df = df.loc[:, ~df.columns.duplicated()]

    if "hydrobasin_level12" not in df.columns:
        raise ValueError("Features-file mist kolom 'hydrobasin_level12'.")

    # Optioneel: forceer exact modelready shared lijst
    shared_features = read_shared_feature_list(shared_features_path)
    if shared_features:
        keep_cols = [c for c in ["hydrobasin_level12", "HYBAS_ID"] if c in df.columns]
        keep_cols += [c for c in shared_features if c in df.columns]
        df = df[keep_cols].copy()

    # 1 rij per basin key
    df["hydrobasin_level12"] = df["hydrobasin_level12"].astype("string").str.replace(r"\.0$", "", regex=True).str.strip()
    df = df.dropna(subset=["hydrobasin_level12"]).drop_duplicates(subset="hydrobasin_level12", keep="first").reset_index(drop=True)

    monthly_cols = [c for c in df.columns if re.search(r"_s(0[1-9]|1[0-2])$", c)]
    monthly_bases = sorted({c.rsplit("_", 1)[0] for c in monthly_cols})

    id_cols = {"hydrobasin_level12", "HYBAS_ID"}
    static_cols = [c for c in df.columns if c not in id_cols and c not in monthly_cols]

    print(f"✅ Features loaded: rows={len(df):,}, cols={len(df.columns)}")
    print(f"   Static cols={len(static_cols)}, Monthly cols={len(monthly_cols)}, Monthly bases={len(monthly_bases)}")

    return df, static_cols, monthly_cols, monthly_bases


def build_joined_features(obs_path: str,
                          df_feats: pd.DataFrame,
                          static_cols: list[str],
                          monthly_cols: list[str],
                          analysis_mode: str) -> pd.DataFrame:
    obs = pd.read_csv(obs_path)

    required = {"wqms_id", "obs", "month", "hydrobasin_level12"}
    missing = required - set(obs.columns)
    if missing:
        raise ValueError(f"Observations-file mist verplichte kolommen: {missing}")

    obs["hydrobasin_level12"] = obs["hydrobasin_level12"].astype("string").str.replace(r"\.0$", "", regex=True).str.strip()
    obs = obs[obs["hydrobasin_level12"].notna()].copy()

    # Alleen valide maanden
    obs["month"] = pd.to_numeric(obs["month"], errors="coerce")
    obs = obs[obs["month"].between(1, 12, inclusive="both")].copy()
    obs["month"] = obs["month"].astype(int)

    # Alleen basins waar features voor bestaan
    obs = obs[obs["hydrobasin_level12"].isin(df_feats["hydrobasin_level12"])].copy()
    if obs.empty:
        return obs

    # static merge
    overlap = set(obs.columns) & set(static_cols)
    static_no_overlap = [c for c in static_cols if c not in overlap]

    base = obs.merge(
        df_feats[["hydrobasin_level12"] + static_no_overlap],
        on="hydrobasin_level12",
        how="left",
        validate="m:1"
    )

    # maandmapping: var_sMM -> var
    if monthly_cols:
        rows = []
        for m in range(1, 13):
            part = base.loc[base["month"] == m].copy()
            if part.empty:
                continue
            suffix = f"_s{m:02d}"
            mcols = [c for c in monthly_cols if c.endswith(suffix)]
            if not mcols:
                rows.append(part)
                continue

            feats_m = df_feats[["hydrobasin_level12"] + mcols].copy()
            feats_m = feats_m.rename(columns={c: c.rsplit("_", 1)[0] for c in mcols})

            joined = part.merge(feats_m, on="hydrobasin_level12", how="left", validate="m:1")
            rows.append(joined)

        df_full = pd.concat(rows, ignore_index=True) if rows else base.copy()

        # verwijder overgebleven _sMM kolommen
        drop_mm = [c for c in df_full.columns if re.search(r"_s(0[1-9]|1[0-2])$", c)]
        df_full = df_full.drop(columns=drop_mm, errors="ignore")
    else:
        df_full = base

    # Geofilter voor EU-mode
    if analysis_mode == "EU_train_NL_test" and COUNTRY_FIELD in df_full.columns:
        before = len(df_full)
        df_full = df_full[df_full[COUNTRY_FIELD].isin(EUROPE_COUNTRIES)].copy()
        print(f"EU-filter: {before:,} -> {len(df_full):,}")

    # Kolomnamen opschonen
    df_full.columns = df_full.columns.str.strip()
    df_full = df_full.loc[:, ~df_full.columns.duplicated()]

    return df_full


