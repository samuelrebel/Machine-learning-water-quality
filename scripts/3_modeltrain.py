def update_fi_summary(fi_path: str, fi_summary_path: str):
    if not os.path.exists(fi_path):
        return
    fi = pd.read_csv(fi_path)
    if fi.empty:
        return
    if "Feature_label" not in fi.columns:
        fi["Feature_label"] = fi["Feature"].map(feature_label)

    summary = (fi.groupby(["Variable", "CV_type", "Feature", "Feature_label"], as_index=False)
                 .agg(Importance_mean=("Importance", "mean"),
                      Importance_std=("Importance", "std"),
                      Obs_sum=("Obs.", "sum")))
    atomic_to_csv(summary, fi_summary_path)


