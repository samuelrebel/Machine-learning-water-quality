# Climatology aggregatie (median) met behoud schema
# -------------------------------------------------
def aggregate_to_site_month_median_preserve_schema(df: pd.DataFrame) -> pd.DataFrame:
    """
    1 rij per (wqms_id, month) met mediane 'obs' over alle jaren,
    met behoud van dezelfde kolommen als input.

    - 'obs' := median(obs) (na numeric coercion)
    - 'year', 'year_month', 'dates' van het LAATSTE jaar in de groep
    - overige kolommen via 'first'
    """
    required = {"wqms_id", "month", "year", "obs", "dates"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Ontbrekende kolommen voor aggregatie: {missing}")

    df = df.copy()
    df["dates"] = pd.to_datetime(df["dates"], errors="coerce")

    # zorg dat obs numeriek is voor median
    df["obs"] = pd.to_numeric(df["obs"], errors="coerce")

    med = (
        df.groupby(["wqms_id", "month"])["obs"]
          .median()
          .rename("obs_median")
    )

    idx_max_year = (
        df.sort_values(["wqms_id", "month", "year"], ascending=[True, True, True])
          .groupby(["wqms_id", "month"], as_index=False)
          .tail(1)
          .set_index(["wqms_id", "month"])
    )

    firsts = (
        df.sort_values(["wqms_id", "month"])
          .groupby(["wqms_id", "month"], as_index=False)
          .first()
          .set_index(["wqms_id", "month"])
    )

    out = firsts.join(med, how="left")
    out["obs"] = out["obs_median"]
    out = out.drop(columns=["obs_median"], errors="ignore")

    for col in ["year", "dates", "year_month"]:
        if col in out.columns and col in idx_max_year.columns:
            out[col] = idx_max_year[col]

    if "dates" in out.columns:
        out["dates"] = pd.to_datetime(out["dates"], errors="coerce")
        if "year" in out.columns:
            out["year"] = out["dates"].dt.year
        if "year_month" in out.columns:
            out["year_month"] = out["dates"].dt.to_period("M").astype(str)

    out = out.reset_index()
    out["obs"] = pd.to_numeric(out["obs"], errors="coerce")
    return out

