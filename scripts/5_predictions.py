def simplify_cv_type(cv):
    if pd.isna(cv):
        return cv
    return re.sub(r"\s*\(.*\)\s*$", "", str(cv)).strip()


def is_lower_better(metric: str) -> bool:
    m = metric.upper()
    return m.startswith("NRMSE") or m.endswith("RMSE")


def resolve_existing_path(candidates: list[str], label: str) -> str:
    for path in candidates:
        if os.path.exists(path):
            print(f"✅ {label}: {path}")
            return path
    raise FileNotFoundError(f"Geen bestand gevonden voor {label}. Geprobeerd: {candidates}")


def load_scores_for_topn(path: str, source_label: str) -> pd.DataFrame:
    if not os.path.exists(path):
        raise FileNotFoundError(f"Score-file niet gevonden: {path}")
    df = pd.read_csv(path)
    if "Obs." in df.columns and "Obs" not in df.columns:
        df = df.rename(columns={"Obs.": "Obs"})

    required = {"Variable", "CV_type", "Fold", "Obs", RANK_METRIC}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Scores missen kolommen in {path}: {missing}")

    for c in ["Fold", "Obs", "R2", "RMSE", "NRMSE_mean", "NRMSE_range", "NRMSE_std"]:
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce")

    df["Source"] = source_label
    df["CV_type"] = df["CV_type"].apply(simplify_cv_type)
    df = df[~df["CV_type"].isin(EXCLUDE_CV_TYPES)].copy()
    return df


def get_top_constituents_from_scores(top_n: int):
    scores_world = resolve_existing_path(SCORES_WORLD_CANDIDATES, "scores WORLD_all")
    scores_eu_nl = resolve_existing_path(SCORES_EU_NL_CANDIDATES, "scores EU_train_NL_test")
    df_world = load_scores_for_topn(scores_world, "WORLD_all")
    df_eu_nl = load_scores_for_topn(scores_eu_nl, "EU_train_NL_test")
    df = pd.concat([df_world, df_eu_nl], ignore_index=True)

    cv_agg = (
        df.groupby(["Source", "Variable", "CV_type"], as_index=False)
          .agg(
              metric_med=(RANK_METRIC, "median"),
              n_med=("Obs", "median"),
              folds=("Fold", "nunique"),
          )
    )
    cv_agg["n_min_required"] = cv_agg["Source"].map(N_MIN)
    cv_agg = cv_agg[(cv_agg["n_med"] >= cv_agg["n_min_required"]) & (cv_agg["folds"] >= MIN_FOLDS_PER_CV)].copy()

    var_agg = (
        cv_agg.groupby(["Source", "Variable"], as_index=False)
              .agg(metric_overall=("metric_med", "median"))
    )

    lower = is_lower_better(RANK_METRIC)
    top_world = (
        var_agg[var_agg["Source"] == "WORLD_all"]
        .sort_values("metric_overall", ascending=lower)
        .head(top_n)["Variable"]
        .tolist()
    )
    top_eu_nl = (
        var_agg[var_agg["Source"] == "EU_train_NL_test"]
        .sort_values("metric_overall", ascending=lower)
        .head(top_n)["Variable"]
        .tolist()
    )

    return set(top_world), set(top_eu_nl)


def run_scenario(scenario_name: str,
                 train_scope: str,
                 train_features: pd.DataFrame,
                 train_static_cols: list[str],
                 train_monthly_cols: list[str],
                 predict_features: pd.DataFrame,
                 predict_static_cols: list[str],
                 predict_monthly_cols: list[str],
                 obs_dir: str,
                 out_dir: str,
                 allowed_constituents: set[str] | None = None) -> pd.DataFrame:
    Path(out_dir).mkdir(parents=True, exist_ok=True)

    wide_path = os.path.join(out_dir, f"predictions_{scenario_name}_wide.csv")
    log_path = os.path.join(out_dir, f"training_log_{scenario_name}.csv")

    pollutant_files = list_pollutant_files(obs_dir)
    if allowed_constituents is not None:
        pollutant_files = [
            p for p in pollutant_files
            if os.path.splitext(os.path.basename(p))[0] in allowed_constituents
        ]
    print(f"\n=== Scenario: {scenario_name} ===")
    print(f"Pollutant files (na top-N filter): {len(pollutant_files)}")

    # NL predict subset voor EU->NL scenario
    pred_feat_use = predict_features.copy()
    if scenario_name == "EU_train_NL_predict":
        nl_keys, method = get_nl_basin_keys(obs_dir)
        print(f"NL basin key method: {method} | keys={len(nl_keys):,}")
        if len(nl_keys) == 0:
            raise ValueError("Geen NL basin keys gevonden voor EU_train_NL_predict")
        pred_feat_use = pred_feat_use[pred_feat_use["hydrobasin_level12"].isin(nl_keys)].copy()
        print(f"NL basins in prediction set: {len(pred_feat_use):,}")

    # Wide basis laden/opzetten (checkpoint-friendly): behoud bestaande prediction-kolommen.
    meta_cols = [c for c in ["hydrobasin_level12", "HYBAS_ID"] if c in pred_feat_use.columns]
    wide_df = load_or_initialize_wide_predictions(
        wide_path=wide_path,
        pred_feat_use=pred_feat_use,
        meta_cols=meta_cols,
    )

    # Resume: skip alleen constituents die daadwerkelijk alle 12 maandkolommen in de wide CSV hebben.
    # Vertrouw niet alleen op training_log: een oude/halve run kan daar "ok" hebben staan terwijl de
    # prediction-kolommen ontbreken. Dan moeten we juist opnieuw voorspellen, anders ontstaan er geen maps.
    processed = set()
    log_ok_vars = set()
    if os.path.exists(log_path):
        try:
            log_old = pd.read_csv(log_path)
            if "variable" in log_old.columns and "status" in log_old.columns:
                log_ok_vars = set(
                    log_old.loc[
                        log_old["status"].astype(str).str.startswith("ok"),
                        "variable"
                    ].dropna().astype(str).unique().tolist()
                )
        except Exception as e:
            print(f"⚠️ Kon bestaande training_log niet lezen voor resume: {e}")

    missing_wide_cols_after_log_ok = []
    for p in pollutant_files:
        var = os.path.splitext(os.path.basename(p))[0]
        mcols = variable_month_cols(var)
        has_all_month_cols = all(c in wide_df.columns for c in mcols)
        if has_all_month_cols:
            processed.add(var)
        elif var in log_ok_vars:
            missing_wide_cols_after_log_ok.append(var)

    if processed:
        print(f"Resume actief: {len(processed)} constituents met complete wide voorspellingen worden overgeslagen.")
    if missing_wide_cols_after_log_ok:
        print(
            f"⚠️ {len(missing_wide_cols_after_log_ok)} constituents stonden als ok in training_log, "
            "maar missen maandkolommen in de wide CSV; deze worden opnieuw voorspeld."
        )
        print(f"Voorbeelden opnieuw voorspellen: {missing_wide_cols_after_log_ok[:8]}")

    for p in pollutant_files:
        fname = os.path.basename(p)
        variable = os.path.splitext(fname)[0]
        if variable in processed:
            print(f"⏩ Skip {variable} (al verwerkt)")
            continue

        try:
            train_df = build_training_table(
                obs_path=p,
                feat_df=train_features,
                static_cols=train_static_cols,
                monthly_cols=train_monthly_cols,
                train_scope=train_scope,
            )
            if train_df.empty:
                append_to_csv(pd.DataFrame([{
                    "variable": variable, "status": "skip_empty_after_join", "train_rows": 0
                }]), log_path)
                continue

            train_df["obs"] = pd.to_numeric(train_df["obs"], errors="coerce")
            train_df = train_df[train_df["obs"].notna()].copy()
            if train_df.empty:
                append_to_csv(pd.DataFrame([{
                    "variable": variable, "status": "skip_all_obs_nan", "train_rows": 0
                }]), log_path)
                continue

            feature_cols = prepare_feature_columns(train_df)
            if not feature_cols:
                append_to_csv(pd.DataFrame([{
                    "variable": variable, "status": "skip_no_features", "train_rows": len(train_df)
                }]), log_path)
                continue

            # Fit imputation stats op train
            mainbas_medians, global_medians = fit_imputation_stats(train_df, feature_cols)
            X_train = apply_imputation(train_df, feature_cols, mainbas_medians, global_medians)
            y_train = train_df["obs"].astype(np.float32).to_numpy()

            # Train model
            model = cuRF(n_estimators=N_ESTIMATORS, random_state=SEED, n_streams=1)
            model.fit(cudf.DataFrame(X_train), cudf.Series(y_train))

            # Predict alle maanden -> direct naar wide-kolommen
            var_pred = pd.DataFrame({"hydrobasin_level12": pred_feat_use["hydrobasin_level12"].values})
            for m in range(1, 13):
                pred_tbl = build_predict_table_for_month(
                    feat_df=pred_feat_use,
                    static_cols=predict_static_cols,
                    monthly_cols=predict_monthly_cols,
                    month=m,
                )

                # Zorg dat alle train feature_cols bestaan
                for c in feature_cols:
                    if c not in pred_tbl.columns:
                        pred_tbl[c] = np.nan

                X_pred = apply_imputation(pred_tbl, feature_cols, mainbas_medians, global_medians)
                pred_raw = model.predict(cudf.DataFrame(X_pred))
                y_pred = to_numpy_1d(pred_raw)
                var_pred[f"{variable}_{m:02d}"] = y_pred

            # Checkpoint per constituent: voeg 12 maandkolommen toe/vervang ze, behoud alle andere predictions.
            cols_before = len([c for c in wide_df.columns if re.search(r"_(0[1-9]|1[0-2])$", str(c))])
            wide_df = merge_prediction_columns(wide_df, var_pred, variable)
            cols_after = len([c for c in wide_df.columns if re.search(r"_(0[1-9]|1[0-2])$", str(c))])
            atomic_to_csv(wide_df, wide_path)
            print(f"   Wide checkpoint: prediction month columns {cols_before} -> {cols_after}")

            append_to_csv(pd.DataFrame([{
                "variable": variable,
                "status": "ok",
                "train_rows": int(len(train_df)),
                "feature_count": int(len(feature_cols)),
                "predict_basins": int(len(pred_feat_use)),
            }]), log_path)

            print(f"✅ {variable}: opgeslagen in wide ({len(pred_feat_use):,} basins x 12 maanden)")

        except Exception as e:
            print(f"❌ {variable}: prediction mislukt: {e}")
            append_to_csv(pd.DataFrame([{
                "variable": variable,
                "status": f"error: {e}",
                "train_rows": np.nan
            }]), log_path)
            continue

    # Final persist
    atomic_to_csv(wide_df, wide_path)
    pred_cols_final = [c for c in wide_df.columns if re.search(r"_(0[1-9]|1[0-2])$", str(c))]
    print(f"Scenario {scenario_name}: wide prediction columns na run = {len(pred_cols_final)}")
    if not pred_cols_final:
        print(
            "⚠️ Geen prediction-kolommen geschreven. Check de error-regels hierboven en "
            f"het logbestand: {log_path}"
        )
    return wide_df


