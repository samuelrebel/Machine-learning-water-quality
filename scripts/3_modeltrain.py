def compute_feature_importance(model, X_test, y_test, feature_cols, scoring="r2", n_repeats=5):
    res = permutation_importance(
        model, X_test, y_test,
        n_repeats=n_repeats,
        scoring=scoring,
        random_state=SEED
    )
    return pd.DataFrame({
        "Feature": feature_cols,
        "Feature_label": [feature_label(c) for c in feature_cols],
        "Importance": res.importances_mean.astype(np.float32),
        "Importance_std": res.importances_std.astype(np.float32),
    })


def build_grouped_kfold_splits(X, y, clean, group_series, all_idx, n_splits, min_group_size=1, restrict_test_mask=None):
    if restrict_test_mask is not None:
        vc = group_series[restrict_test_mask].value_counts()
    else:
        vc = group_series.value_counts()

    eligible_groups = vc[vc >= min_group_size].index
    if len(eligible_groups) < 2:
        raise ValueError(f"Te weinig geschikte groepen (>= {min_group_size})")

    n_splits_eff = min(n_splits, max(2, len(eligible_groups)))
    gkf = GroupKFold(n_splits=n_splits_eff)

    splits = []
    fold_keys = []

    if restrict_test_mask is None:
        mask = clean.index.isin(all_idx)
        X_use = X[mask]
        y_use = y[mask]
        groups_use = group_series[mask]

        for _, test_pos in gkf.split(X_use, y_use, groups=groups_use):
            idx_all = clean.index[mask].to_numpy()
            test_idx = idx_all[test_pos]
            keep = np.isin(group_series.loc[test_idx].to_numpy(), eligible_groups.to_numpy())
            test_idx = test_idx[keep]
            train_idx = np.setdiff1d(all_idx, test_idx, assume_unique=False)
            splits.append((train_idx, test_idx))
            fold_keys.append(group_series.loc[test_idx].unique().tolist())
    else:
        idx_restricted = clean.index[restrict_test_mask].to_numpy()
        groups_use = group_series[restrict_test_mask]
        is_eligible = groups_use.isin(eligible_groups)

        idx_restricted = idx_restricted[is_eligible.to_numpy()]
        X_use = X[restrict_test_mask][is_eligible.to_numpy()]
        y_use = y[restrict_test_mask][is_eligible.to_numpy()]
        groups_use = groups_use[is_eligible]

        for _, test_pos in gkf.split(X_use, y_use, groups=groups_use):
            test_idx = idx_restricted[test_pos]
            train_idx = np.setdiff1d(all_idx, test_idx, assume_unique=False)
            splits.append((train_idx, test_idx))
            fold_keys.append(group_series.loc[test_idx].unique().tolist())

    return splits, fold_keys


def run_cv_gpu_only(X, y, feature_cols, clean,
                    cv_type="Random CV", group_col=None, n_splits=5,
                    importance_on_cv=("Random CV", "Station CV", "Country CV", "Basin CV"),
                    n_repeats=5, scoring="r2",
                    restrict_test_to_country=None,
                    exclude_country_from_train=None,
                    min_group_size=5):

    if set_global_output_type is not None:
        try:
            set_global_output_type("numpy")
        except Exception:
            pass

    X_gpu = cudf.DataFrame(X, columns=feature_cols)
    models = {
        "RF": lambda: cuRF(n_estimators=200, random_state=SEED, n_streams=1)
    }

    all_idx = np.arange(len(X))
    c_idx = None

    if restrict_test_to_country is not None:
        if COUNTRY_FIELD not in clean.columns:
            raise ValueError(f"Kolom '{COUNTRY_FIELD}' ontbreekt voor NL-testrestrictie")
        c_mask = (clean[COUNTRY_FIELD] == restrict_test_to_country)
        c_idx = np.where(c_mask.values)[0]
        if len(c_idx) == 0:
            raise ValueError(f"Geen rijen voor testland '{restrict_test_to_country}'")

    # splits
    if cv_type == "Random CV":
        if c_idx is None:
            kf = KFold(n_splits=min(n_splits, max(2, len(all_idx))), shuffle=True, random_state=SEED)
            splits = list(kf.split(X))
            fold_keys = list(range(1, len(splits) + 1))
        else:
            n_eff = min(n_splits, max(2, len(c_idx)))
            kf = KFold(n_splits=n_eff, shuffle=True, random_state=SEED)
            splits, fold_keys = [], list(range(1, n_eff + 1))
            for _, test_pos in kf.split(c_idx):
                test_idx = c_idx[test_pos]
                train_idx = np.setdiff1d(all_idx, test_idx, assume_unique=False)
                splits.append((train_idx, test_idx))

    elif cv_type == "Station CV":
        if "wqms_id" not in clean.columns:
            raise ValueError("Station CV vereist kolom 'wqms_id'")

        if c_idx is None:
            groups = clean["wqms_id"]
            n_eff = min(n_splits, max(2, len(groups.unique())))
            gkf = GroupKFold(n_splits=n_eff)
            splits = list(gkf.split(X, y, groups=groups))
            fold_keys = [clean.loc[test_idx, "wqms_id"].unique().tolist() for _, test_idx in splits]
        else:
            groups_c = clean.loc[c_idx, "wqms_id"]
            n_eff = min(n_splits, max(2, len(groups_c.unique())))
            gkf = GroupKFold(n_splits=n_eff)
            splits, fold_keys = [], []
            for _, test_pos in gkf.split(c_idx, y[c_idx], groups=groups_c):
                test_idx = c_idx[test_pos]
                train_idx = np.setdiff1d(all_idx, test_idx, assume_unique=False)
                splits.append((train_idx, test_idx))
                fold_keys.append(clean.loc[test_idx, "wqms_id"].unique().tolist())

    elif cv_type == "Country CV":
        groups = clean[group_col] if group_col else clean[COUNTRY_FIELD]
        restrict_mask = None if c_idx is None else clean.index.isin(c_idx)
        splits, fold_keys = build_grouped_kfold_splits(
            X=X, y=y, clean=clean, group_series=groups, all_idx=all_idx,
            n_splits=n_splits, min_group_size=min_group_size, restrict_test_mask=restrict_mask
        )

    elif cv_type == "Basin CV":
        groups = clean["hydrobasin_level12"]
        restrict_mask = None if c_idx is None else clean.index.isin(c_idx)
        splits, fold_keys = build_grouped_kfold_splits(
            X=X, y=y, clean=clean, group_series=groups, all_idx=all_idx,
            n_splits=n_splits, min_group_size=min_group_size, restrict_test_mask=restrict_mask
        )

    else:
        raise ValueError(f"Onbekende cv_type: {cv_type}")

    perf_rows, fi_rows = [], []
    pollutant = clean["variable"].iat[0] if ("variable" in clean.columns and len(clean)) else "unknown"

    fold = 1
    for fold_label, (train_idx, test_idx) in zip(fold_keys, splits):
        if len(test_idx) < 10:
            continue

        if exclude_country_from_train is not None and COUNTRY_FIELD in clean.columns:
            keep_train = (clean.iloc[train_idx][COUNTRY_FIELD] != exclude_country_from_train).values
            train_idx = train_idx[keep_train]

        if DEBUG_FOLD_COUNTS and restrict_test_to_country is not None and COUNTRY_FIELD in clean.columns:
            n_train = int((clean.iloc[train_idx][COUNTRY_FIELD] == restrict_test_to_country).sum())
            n_test = int((clean.iloc[test_idx][COUNTRY_FIELD] == restrict_test_to_country).sum())
            print(f"  Fold {fold}: NL in train={n_train}, NL in test={n_test}")

        Xte = X[test_idx]
        yte = y[test_idx]

        Xtr_gpu = X_gpu.iloc[train_idx]
        Xte_gpu = X_gpu.iloc[test_idx]
        ytr_gpu = cudf.Series(y[train_idx])

        for model_name, model_builder in models.items():
            model = model_builder()
            model.fit(Xtr_gpu, ytr_gpu)
            pred = np.asarray(model.predict(Xte_gpu))

            rmse, nrmse_mean, nrmse_range, nrmse_std = compute_rmse_and_nrmse(yte, pred)
            r2 = float(r2_score(yte, pred))

            if restrict_test_to_country is None:
                cv_label = cv_type
            else:
                suffix = "NL test; NL excluded" if exclude_country_from_train == restrict_test_to_country else "NL test; NL allowed"
                cv_label = f"{cv_type} ({suffix})"

            perf_rows.append({
                "Fold": fold,
                "Model": model_name,
                "Variable": pollutant,
                "CV_type": cv_label,
                "Obs.": int(len(yte)),
                "R2": r2,
                "R2 (%)": r2 * 100.0,
                "RMSE": rmse,
                "NRMSE_mean": nrmse_mean,
                "NRMSE_range": nrmse_range,
                "NRMSE_std": nrmse_std,
                "Country": restrict_test_to_country if restrict_test_to_country else (fold_label if cv_type == "Country CV" else None),
                "Basin": fold_label if cv_type == "Basin CV" else None,
                "wqms_id": fold_label if cv_type == "Station CV" else None,
            })

            if cv_type in importance_on_cv:
                fi_df = compute_feature_importance(
                    model=model,
                    X_test=Xte,
                    y_test=yte,
                    feature_cols=feature_cols,
                    scoring=scoring,
                    n_repeats=n_repeats,
                )
                fi_df["Fold"] = fold
                fi_df["CV_type"] = cv_label
                fi_df["Model"] = model_name
                fi_df["Variable"] = pollutant
                fi_df["Obs."] = int(len(yte))
                fi_rows.append(fi_df)

        fold += 1

    perf_df = pd.DataFrame(perf_rows)
    fi_all = pd.concat(fi_rows, ignore_index=True) if fi_rows else pd.DataFrame()
    return perf_df, fi_all


