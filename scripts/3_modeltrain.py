def prepare_data(df_full: pd.DataFrame):
    if df_full is None or df_full.empty:
        return None, None, None, []

    if "obs" not in df_full.columns:
        raise ValueError("Kolom 'obs' ontbreekt na join.")

    df = df_full.copy()
    df["obs"] = pd.to_numeric(df["obs"], errors="coerce")

    # Alleen model-features (numeric), zonder identifiers/topologie/categoriecodes.
    exclude = {
        "obs", "variable", "unit", "dates", "year", "year_month", "month",
        "wqms_id", "hydrobasin_level12", "HYBAS_ID", COUNTRY_FIELD,
    }

    feature_cols = [c for c in df.columns if c not in exclude and is_model_predictor_column(c)]
    feature_cols = [c for c in feature_cols if pd.api.types.is_numeric_dtype(df[c])]

    if not feature_cols:
        return None, None, None, []

    mask_good = (~df[feature_cols].isna().all(axis=1)) & (~df["obs"].isna())
    clean = df.loc[mask_good].reset_index(drop=True)
    if clean.empty:
        return None, None, None, feature_cols

    X = clean[feature_cols].copy().replace([np.inf, -np.inf], np.nan)
    miss_before = float(X.isna().mean().mean()) * 100.0

    # 1) Group-aware imputatie (van fijn -> grover)
    # Deze volgorde behoudt zoveel mogelijk hydrologische/regionale context.
    group_order = ["hydrobasin_level12", "MAIN_BAS", COUNTRY_FIELD]
    used_groups = []
    X_imp = X.copy()
    for g in group_order:
        if g in clean.columns:
            grp_med = X_imp.groupby(clean[g]).transform("median")
            X_imp = X_imp.fillna(grp_med)
            used_groups.append(g)

    # 2) Globale median fallback
    med = X_imp.median(numeric_only=True)
    X_imp = X_imp.fillna(med).fillna(0)

    miss_after = float(X_imp.isna().mean().mean()) * 100.0
    print(f"Imputatie: missings {miss_before:.2f}% -> {miss_after:.2f}% | groups={used_groups if used_groups else ['none']}")

    X = X_imp.astype(np.float32)

    y = clean["obs"].astype(np.float32).to_numpy()

    return clean, X, y, feature_cols


