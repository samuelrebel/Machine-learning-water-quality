        cbar.set_label("Predicted concentration")

        fig.suptitle(f"{scenario_name} | {var} | monthly basin predictions", fontsize=16, y=0.995)
        fig.tight_layout(rect=[0, 0, 1, 0.98])

        out_png = os.path.join(out_dir, f"map_{scenario_name}_{var}.png")
        fig.savefig(out_png, dpi=220, bbox_inches="tight")
        plt.close(fig)


