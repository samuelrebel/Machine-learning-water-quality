def atomic_to_csv(df: pd.DataFrame, path: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    dir_name = os.path.dirname(path) or "."
    fd, tmp_path = tempfile.mkstemp(prefix="tmp_", suffix=".csv", dir=dir_name)
    os.close(fd)
    try:
        df.to_csv(tmp_path, index=False)
        os.replace(tmp_path, path)
    finally:
        try:
            if os.path.exists(tmp_path):
                os.remove(tmp_path)
        except Exception:
            pass


def read_shared_feature_list(shared_path: str | None) -> list[str]:
    if not shared_path or not os.path.exists(shared_path):
        return []
    try:
        s = pd.read_csv(shared_path)
        if "feature" not in s.columns:
            return []
        return [str(v) for v in s["feature"].dropna().tolist()]
    except Exception:
        return []


def list_pollutant_files(pollutant_dir: str) -> list[str]:
    """
    Neem alleen pollutant-observaties mee.
    Sluit rapport- en helperbestanden uit die script 2 nu ook wegschrijft.
    """
    files = sorted(glob.glob(os.path.join(pollutant_dir, "*.csv")))
    excluded_exact = {
        "balancing_report_summary.csv",
        "balancing_report_by_country.csv",
    }
    excluded_prefixes = ("features_", "all_results", "feature_importance")

    keep = []
    for p in files:
        b = os.path.basename(p)
        if b in excluded_exact:
            continue
        if any(b.startswith(pref) for pref in excluded_prefixes):
            continue
        keep.append(p)
    return keep


