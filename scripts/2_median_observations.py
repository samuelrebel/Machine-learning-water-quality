def remove_flagged_outliers_df(
    df: pd.DataFrame,
    flag_col: str = "flag",
    outlier_flag_value: str = "*"
) -> pd.DataFrame:
    """
    Verwijder alleen rijen waar flag == '*'.
    Houd rijen met missende flag (NaN/<NA>) expliciet vast.
    """
    if flag_col not in df.columns:
        return df.copy()

    flags = df[flag_col].astype("string")

    # KEEP als: flag is missing OR flag != '*'
    keep = flags.isna() | (flags != outlier_flag_value)

    return df.loc[keep].copy()

def balance_by_top3_countries_df(
    df: pd.DataFrame,
    country_col: str = "country_name",
    random_state: int = 42,
    shuffle: bool = True
) -> pd.DataFrame:
    """
    Downsample top-3 landen naar n = count(3e land).
    Niet-top3 landen blijven volledig behouden.
    """
    if country_col not in df.columns:
        raise ValueError(f"Kolom '{country_col}' ontbreekt in df.")

    counts = df[country_col].value_counts(dropna=False)
    if len(counts) < 3:
        return df.copy()

    top3 = counts.index[:3]
    n_third = int(counts.iloc[2])

    parts = []
    parts.append(df.loc[~df[country_col].isin(top3)])

    for country in top3:
        subset = df.loc[df[country_col] == country]
        if len(subset) <= n_third:
            parts.append(subset)
        else:
            parts.append(subset.sample(n=n_third, random_state=random_state))

    balanced = pd.concat(parts, ignore_index=True)
    if shuffle:
        balanced = balanced.sample(frac=1, random_state=random_state).reset_index(drop=True)
    return balanced

def _country_label(val) -> str:
    if pd.isna(val):
        return "<NA>"
    return str(val)

def build_balancing_report(before_df: pd.DataFrame, after_df: pd.DataFrame, file_name: str, country_col: str):
    """
    Return:
      summary_row: 1 dict per file
      country_rows: meerdere dicts per file/country met before/after counts
    """
    if country_col not in before_df.columns:
        return (
            {
                "file_name": file_name,
                "country_col": country_col,
                "balancing_applied": False,
                "reason": "country_col_missing",
                "rows_before": int(len(before_df)),
                "rows_after": int(len(after_df)),
                "countries_before": 0,
                "countries_after": 0,
                "top3_before": "",
                "target_n_third_before": np.nan,
            },
            []
        )

    before_counts = before_df[country_col].value_counts(dropna=False)
    after_counts = after_df[country_col].value_counts(dropna=False)

    top3_vals = before_counts.index[:3].tolist()
    top3_str = "|".join(_country_label(v) for v in top3_vals)
    n_third = int(before_counts.iloc[2]) if len(before_counts) >= 3 else np.nan

    reason = "balanced" if len(before_counts) >= 3 else "lt_3_countries"
    summary_row = {
        "file_name": file_name,
        "country_col": country_col,
        "balancing_applied": len(before_counts) >= 3,
        "reason": reason,
        "rows_before": int(len(before_df)),
        "rows_after": int(len(after_df)),
        "countries_before": int(before_counts.shape[0]),
        "countries_after": int(after_counts.shape[0]),
        "top3_before": top3_str,
        "target_n_third_before": n_third,
    }

    union_countries = set(before_counts.index.tolist()) | set(after_counts.index.tolist())
    country_rows = []
    for c in sorted(union_countries, key=lambda x: _country_label(x)):
        b = int(before_counts.get(c, 0))
        a = int(after_counts.get(c, 0))
        country_rows.append({
            "file_name": file_name,
            "country_name": _country_label(c),
            "count_before": b,
            "count_after": a,
            "delta_after_minus_before": a - b,
            "downsampled": a < b,
            "upsampled": a > b,
        })

    return summary_row, country_rows

def ensure_geometry(
    df: pd.DataFrame,
    lat_col: str = "wqms_lat",
    lon_col: str = "wqms_lon",
    crs: str = "EPSG:4326",
    auto_swap: bool = False
) -> gpd.GeoDataFrame:
    if isinstance(df, gpd.GeoDataFrame) and "geometry" in df.columns and df.geometry.notna().any():
        gdf = df.copy()
        if gdf.crs is None:
            gdf.set_crs(crs, inplace=True)
        return gdf

    if lat_col not in df.columns or lon_col not in df.columns:
        candidates = [("lat", "lon"), ("latitude", "longitude")]
        for la, lo in candidates:
            if la in df.columns and lo in df.columns:
                lat_col, lon_col = la, lo
                break
        else:
            raise ValueError(f"Geen lat/lon-kolommen gevonden (gezocht: '{lat_col}', '{lon_col}').")

    lat = pd.to_numeric(df[lat_col], errors="coerce")
    lon = pd.to_numeric(df[lon_col], errors="coerce")

    if auto_swap:
        frac_lat_out = (lat.abs() > 90).mean()
        frac_lon_in  = (lon.abs() <= 90).mean()
        if frac_lat_out > 0.5 and frac_lon_in > 0.5:
            lat, lon = lon, lat

    mask_valid = lat.between(-90, 90) & lon.between(-180, 180)
    df2 = df.loc[mask_valid].copy()
    df2["geometry"] = [Point(xy) for xy in zip(lon.loc[mask_valid], lat.loc[mask_valid])]
    return gpd.GeoDataFrame(df2, geometry="geometry", crs=crs)

def apply_year_filter(
    df: pd.DataFrame,
    col: str = "dates",
    start_year: int = 2010,
    end_year_excl: int = 2024
) -> pd.DataFrame:
    if col not in df.columns:
        raise ValueError(f"Kolom '{col}' ontbreekt.")
    out = df.copy()
    out[col] = pd.to_datetime(out[col], errors="coerce", utc=True).dt.tz_convert(None)
    mask = (out[col].dt.year >= start_year) & (out[col].dt.year < end_year_excl)
    return out.loc[mask].copy()

def add_calendar_cols(df: pd.DataFrame, date_col: str = "dates") -> pd.DataFrame:
    out = df.copy()
    out[date_col] = pd.to_datetime(out[date_col], errors="coerce")
    out["year"] = out[date_col].dt.year
    out["month"] = out[date_col].dt.month
    out["year_month"] = out[date_col].dt.to_period("M").astype(str)
    return out

def landmask_natural_earth(gdf: gpd.GeoDataFrame) -> gpd.GeoDataFrame:
    """Optioneel: filter punten op land met Natural Earth 'land' 110m (vereist cartopy/shapely)."""
    try:
        import cartopy.feature as cfeature
        from shapely.ops import unary_union
    except Exception as e:
        raise ImportError("Voor landmask heb je 'cartopy' en 'shapely' nodig.") from e

    land_feat = cfeature.NaturalEarthFeature("physical", "land", "110m")
    land_geom = unary_union(list(land_feat.geometries()))

    pts = gdf.to_crs(epsg=4326).copy()
    mask = pts.geometry.apply(
        lambda geom: geom.is_valid and geom.within(land_geom) if geom is not None else False
    )
    return pts.loc[mask].copy()

